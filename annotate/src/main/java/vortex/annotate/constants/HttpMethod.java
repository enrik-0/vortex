package vortex.annotate.constants;

/**
 * enumeration of the possible HttpMethods
 */
public enum HttpMethod {


    /**
     * Get method
     */
	GET,
	/**
	 * Post method
	 */
	POST, 
	/**
	 * Put method
	 */
	PUT, 
	/**
	 * Delete method
	 */
	DELETE, 
	/**
	 * Patch method
	 */
	PATCH, 
	/**
	 * Options method
	 */
	OPTIONS, 
	/**
	 * Head method
	 */
	HEAD, 
	/**
	 * Trace method
	 */
	TRACE,
	/**
	 * Connect method
	 */
	CONNECT;

}
